SELECT COUNT(customer_number) AS total_customers FROM gold.dim_customers;

--total number of customers placed an order
SELECT COUNT(DISTINCT customer_key) AS customers FROM gold.fact_sales;


-- Key Metrices of the business
SELECT 'Total Sales' AS measure_name, SUM(sales_amount) AS measure_value FROM gold.fact_sales
UNION 
SELECT 'Total Quantity', SUM(quantity) FROM gold.fact_sales
UNION 
SELECT 'Average Price', AVG(price) FROM gold.fact_sales
UNION
SELECT 'Total Orders', COUNT(DISTINCT order_number) FROM gold.fact_sales
UNION
SELECT 'Total Products', COUNT(product_number) FROM gold.dim_products
UNION
SELECT 'Total Customers', COUNT(customer_number) FROM gold.dim_customers;


-->>>>>>>>>>>>>>
--magnitude analysis -- ita about comparing measure values by categories (aggregated[Measure] by [Dimension])
-->>>>>>>>>>>>>>

-- total customers by country
SELECT country, COUNT(customer_number) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC

--total customers by gender
SELECT gender, COUNT(customer_number) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC

--total products by category
SELECT category, COUNT(product_number) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC;

--average costs in each category
SELECT category, AVG(cost) AS average_cost
FROM gold.dim_products
GROUP BY category
ORDER BY average_cost DESC;

--total revenue generated in each category
SELECT pr.category, SUM(fs.sales_amount) AS total_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_products pr
	ON fs.product_key = pr.product_key
GROUP BY pr.category
ORDER BY total_revenue DESC

--total revenue generated by each customer
SELECT cu.customer_number, cu.first_name,cu.last_name, SUM(fs.sales_amount) AS total_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu
	ON fs.customer_key = cu.customer_key
GROUP BY cu.customer_number, cu.first_name,cu.last_name
ORDER BY total_revenue DESC

--distribution of sold items across countries
SELECT cu.country, SUM(fs.quantity) AS total_quantity
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu
	ON fs.customer_key = cu.customer_key
GROUP BY cu.country
ORDER BY total_quantity DESC


-->>>>>>>>>>>>>>
--Ranking Analysis -- ita about ordering the values of dimensions by measure (Rank[dimension] by aggregated[measure])
-->>>>>>>>>>>>>>

-- top 5 products generating the highest revenue
SELECT TOP 5
pr.product_number,
pr.product_name,
SUM(fs.sales_amount) AS product_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_products pr
	ON fs.product_key = pr.product_key
GROUP BY pr.product_number,pr.product_name
ORDER BY product_revenue DESC

--using window function
SELECT 
*
FROM(
	SELECT 
	pr.product_number,
	pr.product_name,
	SUM(fs.sales_amount) AS product_revenue,
	DENSE_RANK() OVER(ORDER BY SUM(fs.sales_amount) DESC) AS product_rank
	FROM gold.fact_sales fs
	LEFT JOIN gold.dim_products pr
		ON fs.product_key = pr.product_key
	GROUP BY pr.product_number,pr.product_name
)t WHERE product_rank <=5



-- top 5 worst performing products in terms of sales
SELECT TOP 5
pr.product_number,
pr.product_name,
SUM(fs.sales_amount) AS product_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_products pr
	ON fs.product_key = pr.product_key
GROUP BY pr.product_number,pr.product_name
ORDER BY product_revenue 


--top 10 customers who have generated the highest revenue
SELECT TOP 10
cu.customer_number,
cu.first_name,
cu.last_name,
SUM(fs.sales_amount) AS revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu
	ON fs.customer_key = cu.customer_key
GROUP BY cu.customer_number,cu.first_name,cu.last_name
ORDER BY revenue DESC

--top 3 customers with the fewest orders
SELECT TOP 3
cu.customer_number,
cu.first_name,
cu.last_name,
COUNT(DISTINCT fs.order_number) AS total_orders
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu
	ON fs.customer_key = cu.customer_key
GROUP BY cu.customer_number,
cu.first_name,
cu.last_name
ORDER BY total_orders;

